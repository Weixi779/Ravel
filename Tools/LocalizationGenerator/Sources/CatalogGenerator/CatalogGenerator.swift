import Foundation

public struct CatalogError: Error, CustomStringConvertible {
    public let description: String
    init(_ description: String) {
        self.description = description
    }
}

/// Delegates catalog parsing and typed accessor generation to Xcode.
public enum CatalogGenerator {
    public static func generate(catalog: URL) throws -> String {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/xcrun")
        process.arguments = ["xcstringstool", "generate-symbols", catalog.path,
                             "--output-directory", directory.path, "--language", "swift"]
        try process.run()
        process.waitUntilExit()
        guard process.terminationStatus == 0 else { throw CatalogError("Xcode could not generate string symbols.") }
        let files = try FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)
            .filter { $0.pathExtension == "swift" }
        guard files.count == 1 else { throw CatalogError("Expected one generated Swift file for the catalog.") }
        return try exposeSymbols(String(contentsOf: files[0], encoding: .utf8))
    }

    /// Publishes Apple's accessors under our namespace for the macOS 15 package.
    /// Fail explicitly if a future Xcode changes this generated declaration shape.
    public static func exposeSymbols(_ source: String) throws -> String {
        let declaration = "nonisolated extension LocalizedStringResource {"
        guard source.components(separatedBy: declaration).count == 2,
              source.contains("Foundation.Bundle.module"),
              !source.contains("public static ")
        else {
            throw CatalogError("Xcode's generated symbol format changed. Review the I18n adapter before regenerating.")
        }
        let result = source.replacingOccurrences(of: declaration, with: "public nonisolated enum I18n {")
            .replacingOccurrences(of: "\n    static var ", with: "\n    public static var ")
            .replacingOccurrences(of: "\n    static func ", with: "\n    public static func ")
            // This availability is already covered by the package's deployment target.
            .replacingOccurrences(of: "@available(macOS 13, iOS 16, tvOS 16, watchOS 9, *)\n", with: "")
        return "// Generated by Tools/updateLocalization. Edit Localizable.xcstrings instead.\n" + result + "\n"
    }
}
